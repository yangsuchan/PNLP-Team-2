"""AI grading of free-text answers with SCoT's prompt (utils/Eval_SCoT_LLM_Score.py).

SCoT sends two answers, the reference, and the scene image to a judge, which gives each
answer three scores from 1 to 10. The wording here is unchanged; only the judge model differs.
"""

from __future__ import annotations

import hashlib
import re
from typing import Any

CRITERIA = ("Explainability", "Trustworthiness", "Faithfulness")
JUDGE_SYSTEM = (
    "You are a fair and impartial expert evaluator responsible for scoring the explainability, "
    "trustworthiness (convincingness of the answer), and factual support of the two answers "
    "generated by the 3D large language models (on a scale of 1 to 10, with decimals allowed). "
)
_CRITERIA_TEXT = """
    (1) Explainability refers to the degree to which the model’s output, particularly its reasoning process, is clear, well-structured, and easily understandable to human evaluators. High explainability means that each reasoning step can be followed logically, and the path from input to answer is transparent and explicit.
    (2) Trustworthiness measures the extent to which the model’s output, including both the reasoning process and the final answer, is convincing and credible to human evaluators. A trustworthy or persuasive answer not only provides the correct information, but also presents it in a manner that increases user confidence in the correctness and reliability of the output.
    (3) Faithfulness to Facts assesses whether the reasoning steps and final answer produced by the model are strictly grounded in the input information and verifiable facts, without introducing hallucinations, unsupported claims, or factual errors. High faithfulness indicates that all reasoning and conclusions can be traced back to real, reliable evidence. 
    """
_FORMAT_TEXT = """The output must strictly adhere to the following format (where X.X represents a numerical score between 1 and 10, with one decimal place allowed):
    {
    Answer-1 Explainability: X.X
    Answer-1 Trustworthiness: X.X
    Answer-1 Faithfulness: X.X
    Answer-2 Explainability: X.X
    Answer-2 Trustworthiness: X.X
    Answer-2 Faithfulness: X.X
    }"""
_SCORE = re.compile(r"Answer-([12])\s+(Explainability|Trustworthiness|Faithfulness)\W+(\d+(?:\.\d+)?)", re.IGNORECASE)
MAX_ANSWER_WORDS = 1500  # A runaway answer can reach 32,768 tokens; the judge needs only its start to fail it.


# RAGAS AnswerAccuracy (explodinggradients/ragas 298b6827, src/ragas/metrics/_nv_metrics.py), the metric
# on which arXiv 2510.09738 tested judges against human grading. Wording unchanged. Used for training labels.
ACCURACY_TEMPLATE_1 = (
    'Instruction: You are a world class state of the art assistant for rating a User Answer given a Question. The Question is completely answered by the Reference Answer.\n'
    'Say 4, if User Answer is full contained and equivalent to Reference Answerin all terms, topics, numbers, metrics, dates and units.\n'
    'Say 2, if User Answer is partially contained and almost equivalent to Reference Answerin all terms, topics, numbers, metrics, dates and units.\n'
    'Say 0, if User Answer is not contained in Reference Answer or not accurate in all terms, topics,numbers, metrics, dates and units or the User Answer do not answer the question.\n'
    'Do not explain or justify your rating. Your rating must be only 4, 2 or 0 according to the instructions above.\n'
    '### Question: {query}\n'
    '### {answer0}: {sentence_inference}\n'
    '### {answer1}: {sentence_true}\n'
    'The rating is:\n'
)
ACCURACY_TEMPLATE_2 = (
    'I will rate the User Answer in comparison to the Reference Answer for a given Question.\n'
    'A rating of 4 indicates that the User Answer is entirely consistent with the Reference Answer, covering all aspects, topics, numbers, metrics, dates, and units.\n'
    'A rating of 2 signifies that the User Answer is mostly aligned with the Reference Answer, with minor discrepancies in some areas.\n'
    'A rating of 0 means that the User Answer is either inaccurate, incomplete, or unrelated to the Reference Answer, or it fails to address the Question.\n'
    'I will provide the rating without any explanation or justification, adhering to the following scale: 0 (no match), 2 (partial match), 4 (exact match).\n'
    'Do not explain or justify my rating. My rating must be only 4, 2 or 0 only.\n'
    '\n'
    'Question: {query}\n'
    '\n'
    '{answer0}: {sentence_inference}\n'
    '\n'
    '{answer1}: {sentence_true}\n'
    '\n'
    'Rating: '
)
ACCURACY_MAX_TOKENS = 8  # RAGAS expects the rating within the first 8 tokens.
ACCURACY_CORRECT = 0.5  # Partial alignment or better, on the metric's own 0, 2, 4 scale.


def accuracy_prompts(question: str, answer: str, reference: str) -> tuple[str, str]:
    """The metric's two prompts: the answer against the reference, then with the order reversed."""
    return (
        ACCURACY_TEMPLATE_1.format(
            query=question, answer0="User Answer", answer1="Reference Answer", sentence_inference=answer, sentence_true=reference
        ),
        ACCURACY_TEMPLATE_2.format(
            query=question, answer0="Reference Answer", answer1="User Answer", sentence_inference=reference, sentence_true=answer
        ),
    )


def accuracy_rating(reply: str) -> float | None:
    """RAGAS process_score: the lowest digit from 0 to 4 in the reply, over 4. None if there is none."""
    return next((i / 4 for i in range(5) if str(i) in reply), None)


def answer_accuracy(rating_1: float | None, rating_2: float | None) -> float | None:
    """RAGAS average_scores: the mean of both, or the one that exists."""
    valid = [r for r in (rating_1, rating_2) if r is not None]
    if not valid:
        return None
    return sum(valid) / len(valid)


def judge_prompt(question: str, reference: str, answer_1: str, answer_2: str) -> str:
    """SCoT's user prompt, in its order."""
    return (
        _CRITERIA_TEXT
        + f"The query is: <Question-Start> {question}<Question-End>. "
        + f"The ground truth answer is: <Start-Answer-GT> {reference}<End-Answer-GT>. "
        + f"The Answer-1 is: <Start-Answer-1> {answer_1}<End-Answer-1>. "
        + f"The Answer-2  is: <Start-Answer-2> {answer_2}<End-Answer-2>. "
        + _FORMAT_TEXT
    )


def clip_answer(text: str) -> str:
    """Keep a runaway answer from filling the judge's memory."""
    words = text.split(" ")
    return text if len(words) <= MAX_ANSWER_WORDS else " ".join(words[:MAX_ANSWER_WORDS])


def parse_scores(text: str) -> dict[int, dict[str, float]] | None:
    """Scores by answer position, or None unless all six are present and between 1 and 10."""
    scores: dict[int, dict[str, float]] = {1: {}, 2: {}}
    for position, criterion, value in _SCORE.findall(text):
        scores[int(position)][criterion.capitalize()] = float(value)
    complete = all(set(scores[p]) == set(CRITERIA) for p in scores)
    in_range = all(1.0 <= v <= 10.0 for p in scores for v in scores[p].values())
    return scores if complete and in_range else None


def scores_complete(text: str) -> bool:
    """Whether all six scores are written and the last number cannot still grow."""
    return bool(text) and text[-1] not in "0123456789." and parse_scores(text) is not None


def is_swapped(sample_id: str, pair: str, seed: int = 1234) -> bool:
    """Whether the pair's second arm is shown first, fixed per question to cancel position bias."""
    return int(hashlib.sha1(f"{seed}:{sample_id}:{pair}".encode()).hexdigest(), 16) % 2 == 1


def by_arm(scores: dict[int, dict[str, float]], first: str, second: str, swapped: bool) -> dict[str, Any]:
    """Map scores from shown positions back to the arms."""
    return {first: scores[2 if swapped else 1], second: scores[1 if swapped else 2]}
